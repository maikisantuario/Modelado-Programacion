/**
 * Enumeración que define los tipos de masa disponibles para las pizzas
 * en la pizzería "El Pequeño Cesarin".
 */
public enum TipoMasa {
    
    /**
     * Masa de estilo napolitano, tradicional y delgada.
     */
    NAPOLITANA,
    
    /**
     * Masa de estilo romano, muvho mas crujiente.
     */
    ROMANA,
    
    /**
     * Masa de estilo americano, mas gruesa y  mas esponjosa.
     */
    AMERICANA
}